"""Turn the record collection Excel file into the encrypted data file used by nils.westerholt.dk.

Usage:  NILS_KODE=<the Nils password> python3 tools/opdater-samling.py <Musikarkiv.xlsx>

The collection is gzipped and encrypted with a key made from the password, because this
repository is public. Only the server (functions/_middleware.js) can decrypt it,
using the password from a logged-in visitor's cookie.
"""
import base64
import datetime
import gzip
import hashlib
import json
import os
import re
import sys

import openpyxl
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

OUT = os.path.join(os.path.dirname(__file__), "..", "data", "samling.js")
SHEETS = {"Vinyl": "Vinyl", "CD": "CD"}

# Friendly labels for the Excel columns (by header text, or by column letter when the header is empty).
LABELS = {
    "ARTIST": "Kunstner", "ALBUM": "Album", "MEDIA": "Format", "No": "Antal",
    "Year:": "År", "Month:": "Måned", "Date:": "Dag", "*": "Mærke", "I": "Mærke",
    "J": "Kode", "Cover": "Cover", "NOTES": "Noter", "M": "Markering",
}
SKIP = {"YY:"}  # two-digit year, shown as "År" instead


def clean(v):
    if v is None:
        return None
    if isinstance(v, float) and v.is_integer():
        v = int(v)
    s = str(v).strip()
    return s or None


def find_version(wb, filename):
    for ws in wb:
        for row in ws.iter_rows(min_row=1, max_row=1, values_only=True):
            for v in row:
                m = re.search(r"opdateret:?\s*(\d{6})", str(v or ""), re.I)
                if m:
                    return m.group(1)
    m = re.search(r"v(\d{6})", filename)
    return m.group(1) if m else None


def main(path):
    password = os.environ.get("NILS_KODE")
    if not password:
        sys.exit("Sæt NILS_KODE til koden for nils.westerholt.dk")
    wb = openpyxl.load_workbook(path, data_only=True)
    records = []
    for sheet, kind in SHEETS.items():
        ws = wb[sheet]
        rows = list(ws.iter_rows(values_only=True))
        header = rows[0]
        for n, row in enumerate(rows[1:], start=2):
            artist, album = clean(row[0]), clean(row[1])
            if not artist and not album:
                continue
            fields = []
            year = None
            for i, v in enumerate(row):
                v = clean(v)
                h = clean(header[i]) if i < len(header) else None
                if v is None or h in SKIP:
                    continue
                if h and h.lower().startswith("senest opdateret"):
                    h = None
                letter = openpyxl.utils.get_column_letter(i + 1)
                label = LABELS.get(h) or LABELS.get(letter) or h or f"Kolonne {letter}"
                if label == "År":
                    year = v
                fields.append([label, v])
            if year is None and len(row) > 4 and clean(row[4]) and str(clean(row[4])).isdigit():
                year = str(1900 + int(clean(row[4])))
                fields.insert(3, ["År", year])
            fields.append(["Række i Excel", f"{sheet}, række {n}"])
            records.append({"t": kind, "a": artist or "", "b": album or "", "m": clean(row[2]) or "",
                            "y": year or "", "f": fields})

    data = {
        "version": find_version(wb, os.path.basename(path)),
        "file": re.sub(r"^[0-9a-f]{8}-", "", os.path.basename(path)),
        "loaded": datetime.date.today().isoformat(),
        "records": records,
    }
    plain = gzip.compress(json.dumps(data, ensure_ascii=False, separators=(",", ":")).encode())
    key = hashlib.sha256(("nils-samling:" + password).encode()).digest()
    iv = os.urandom(12)
    ct = AESGCM(key).encrypt(iv, plain, None)
    with open(OUT, "w") as f:
        f.write("// Encrypted record collection. Generated by tools/opdater-samling.py, do not edit.\n")
        f.write("export default " + json.dumps({"iv": base64.b64encode(iv).decode(),
                                                 "data": base64.b64encode(ct).decode()}) + ";\n")
    counts = {k: sum(r["t"] == k for r in records) for k in SHEETS.values()}
    print(f"{len(records)} plader ({counts}), version {data['version']}, skrevet til {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main(sys.argv[1])
